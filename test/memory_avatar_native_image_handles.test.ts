import './helpers';
import { afterAll, beforeAll, expect, it, vi } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import sharp from 'sharp';
const calls = vi.hoisted(() => ({ model: vi.fn(), transcription: vi.fn() }));
vi.mock('../server/llm/providers', () => ({ makeLLMCall: (...args: unknown[]) => calls.model(...args) }));
vi.mock('../server/stt/file_transcription', () => ({ transcribeAudioFile: (...args: unknown[]) => calls.transcription(...args) }));
import { closeDatabase, initDatabase } from '../db_layer';
import { createMemoryAvatar, getMemoryAvatar } from '../server/memory_avatar/store';
import { avatarMediaDirectory, probeAvatarMedia } from '../server/memory_avatar/media_files';
import { deleteMemoryAvatarMedia, getMemoryAvatarMediaFile, uploadMemoryAvatarMedia } from '../server/memory_avatar/media';
import { getDataRoot } from '../server/config/data_path';
const owner = 'native-handle-synthetic-owner';
const digest = (value: Buffer) => crypto.createHash('sha256').update(value).digest('hex');
let original: Buffer;
beforeAll(async () => {
  expect(getDataRoot()).toContain('lumi_test_');
  expect(getDataRoot().replaceAll('\\', '/')).not.toBe('C:/Users/Administrator/LumiCore-Legal');
  await initDatabase();
  original = fs.readFileSync(path.resolve('public/avatars/lumi-world/lumi-otome-idle.webp'));
  calls.model.mockImplementation(() => { throw new Error('No model in native file lifecycle test'); });
  calls.transcription.mockImplementation(() => { throw new Error('No STT in native file lifecycle test'); });
});
afterAll(async () => { expect(calls.model).not.toHaveBeenCalled(); expect(calls.transcription).not.toHaveBeenCalled(); await closeDatabase(); });
it.each(['webp', 'jpeg', 'png'] as const)('preserves real %s bytes through upload and immediately deletes the original and derivative without native file locks', async format => {
  const bytes = format === 'webp' ? original : await sharp(original)[format]().toBuffer();
  const avatar = await createMemoryAvatar({ userId: owner, name: 'Synthetic native lifecycle', clientRequestId: crypto.randomUUID() });
  const dir = avatarMediaDirectory(owner, avatar.id), input = path.join(dir, '.upload-native-test');
  fs.writeFileSync(input, bytes);
  const uploaded = await uploadMemoryAvatarMedia(owner, avatar.id, { path: input, title: 'Synthetic image only', clientRequestId: crypto.randomUUID(), revision: avatar.revision });
  expect(uploaded.media).toMatchObject({ kind: 'image', status: 'stored', hasThumbnail: true });
  expect(uploaded.avatar.revision).toBe(2);
  expect(fs.existsSync(input)).toBe(false);
  const stored = getMemoryAvatarMediaFile(owner, avatar.id, uploaded.media.id);
  expect(digest(fs.readFileSync(stored.path))).toBe(digest(bytes));
  const thumbnail = getMemoryAvatarMediaFile(owner, avatar.id, uploaded.media.id, 'thumbnail');
  expect((await sharp(fs.readFileSync(thumbnail.path)).metadata()).format).toBe('jpeg');
  const removed = await deleteMemoryAvatarMedia(owner, avatar.id, uploaded.media.id, uploaded.avatar.revision);
  expect(removed.revision).toBe(3);
  expect(getMemoryAvatar(owner, avatar.id)?.payload.media).toEqual([]);
  expect(fs.readdirSync(dir)).toEqual([]);
});
it('keeps malformed-image rejection and removes the rejected temporary original', async () => {
  const avatar = await createMemoryAvatar({ userId: owner, name: 'Malformed synthetic image', clientRequestId: crypto.randomUUID() });
  const dir = avatarMediaDirectory(owner, avatar.id), input = path.join(dir, '.upload-malformed');
  fs.writeFileSync(input, Buffer.from('RIFF1234WEBPnot-a-decodable-image'));
  await expect(uploadMemoryAvatarMedia(owner, avatar.id, { path: input, title: 'Broken synthetic input', clientRequestId: crypto.randomUUID(), revision: 1 })).rejects.toMatchObject({ code: 'media_decode_failed' });
  expect(getMemoryAvatar(owner, avatar.id)?.revision).toBe(1);
  expect(fs.readdirSync(dir)).toEqual([]);
});
it('preserves caller cancellation as AbortError without interpreting an aborted image read as decoding failure', async () => {
  const avatar = await createMemoryAvatar({ userId: owner, name: 'Cancelled synthetic image', clientRequestId: crypto.randomUUID() });
  const input = path.join(avatarMediaDirectory(owner, avatar.id), '.upload-aborted'); fs.writeFileSync(input, original);
  const controller = new AbortController(); controller.abort();
  await expect(probeAvatarMedia(input, controller.signal)).rejects.toMatchObject({ name: 'AbortError' });
  expect(getMemoryAvatar(owner, avatar.id)?.revision).toBe(1);
  fs.rmSync(input); expect(fs.existsSync(input)).toBe(false);
});
